import { readFile,writeFile } from 'node:fs/promises';
const root=new URL('../',import.meta.url);
const properties=JSON.parse(await readFile(new URL('data/properties.json',root),'utf8'));
const {neighbourhoods,settings}=JSON.parse(await readFile(new URL('data/site-content.json',root),'utf8'));
// Keep this seed usable after the original schema as well as the full setup.
// New rental columns get their safe defaults and source descriptions in migration.
const rentalColumns=new Set(['published_at','listing_code','author_id','price_period','rental_term','overview_en','overview_vi','location_en','location_vi','furnishings_en','furnishings_vi','seo_features','whatsapp_phone','zalo_phone']);
const legacy=record=>Object.fromEntries(Object.entries(record).filter(([key])=>!rentalColumns.has(key)));
function sql(value){
  if(value===null)return 'null';
  if(typeof value==='number')return String(value);
  if(typeof value==='boolean')return value?'true':'false';
  if(Array.isArray(value))return `array[${value.map(sql).join(',')}]::text[]`;
  return "'"+String(value).replaceAll("'","''")+"'";
}
function insert(table,records,key){return records.map(record=>`insert into public.${table} (${Object.keys(record).join(',')}) values (${Object.values(record).map(sql).join(',')}) on conflict (${key}) do nothing;`).join('\n');}
const output='-- Generated by npm run seed:generate. Existing CMS edits are preserved.\nbegin;\n'+insert('neighbourhoods',neighbourhoods,'slug')+'\n'+insert('site_settings',[legacy(settings)],'id')+'\n'+insert('properties',properties.map(legacy),'id')+'\ncommit;\n';
await writeFile(new URL('supabase/seed.sql',root),output);console.log(`Prepared ${properties.length} source listings, ${neighbourhoods.length} neighbourhoods, and site settings.`);
